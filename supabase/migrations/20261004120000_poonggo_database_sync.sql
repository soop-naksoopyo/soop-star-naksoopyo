-- Latest Poonggo snapshot per streamer and month.
CREATE TABLE IF NOT EXISTS public.poonggo_monthly_snapshots (
  year_month TEXT NOT NULL,
  streamer_id UUID NOT NULL REFERENCES public.streamers(id) ON DELETE CASCADE,
  soop_id TEXT NOT NULL REFERENCES public.streamers(soop_id) ON DELETE CASCADE,
  nickname TEXT NOT NULL,
  profile_image_url TEXT,
  total_stars INT NOT NULL DEFAULT 0,
  broadcast_hours NUMERIC(10,1) NOT NULL DEFAULT 0,
  fetched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (year_month, streamer_id),
  UNIQUE (year_month, soop_id)
);

ALTER TABLE public.poonggo_monthly_snapshots ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.poonggo_monthly_snapshots TO anon, authenticated;
REVOKE INSERT, UPDATE, DELETE ON public.poonggo_monthly_snapshots FROM anon, authenticated;
DROP POLICY IF EXISTS "Public can read Poonggo monthly snapshots" ON public.poonggo_monthly_snapshots;
CREATE POLICY "Public can read Poonggo monthly snapshots"
  ON public.poonggo_monthly_snapshots FOR SELECT USING (true);

CREATE TABLE IF NOT EXISTS public.poonggo_sync_runs (
  window_start TIMESTAMPTZ NOT NULL,
  shard_index SMALLINT NOT NULL CHECK (shard_index BETWEEN 0 AND 4),
  status TEXT NOT NULL,
  requested_count INT NOT NULL DEFAULT 0,
  fetched_count INT NOT NULL DEFAULT 0,
  failed_count INT NOT NULL DEFAULT 0,
  duration_ms INT NOT NULL DEFAULT 0,
  error_message TEXT,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (window_start, shard_index)
);

ALTER TABLE public.poonggo_sync_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.poonggo_sync_runs FROM anon, authenticated;


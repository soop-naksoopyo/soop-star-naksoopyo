INSERT INTO public.streamers (soop_id, nickname, profile_image_url, crew_id, is_active)
SELECT roster.soop_id, roster.nickname, roster.profile_image_url, crews.id, true
FROM roster
JOIN public.crews AS crews ON crews.name = roster.crew_name
ON CONFLICT (soop_id) DO UPDATE SET
  nickname = EXCLUDED.nickname,
  profile_image_url = EXCLUDED.profile_image_url,
  crew_id = EXCLUDED.crew_id,
  is_active = true;
